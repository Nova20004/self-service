#!/usr/bin/env bash
# Generate a local .env with fresh random secrets. Never overwrites an
# existing file. Called by `make env`.
set -euo pipefail

TARGET="${1:-.env}"
if [ -e "${TARGET}" ]; then
  echo "${TARGET} already exists; leaving it untouched (delete it to regenerate)."
  exit 0
fi

rand() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -hex 24
  else
    python3 -c 'import secrets; print(secrets.token_hex(24))'
  fi
}

# The socket-proxy containers run as uid 65534 with the group that owns the
# Docker socket: `docker` on Linux, root (0) inside the Docker Desktop VM.
socket_gid=0
if [ "$(uname -s)" = "Linux" ] && [ -S /var/run/docker.sock ]; then
  socket_gid=$(stat -c '%g' /var/run/docker.sock)
fi

umask 077
cat > "${TARGET}" <<EOF
# Generated by \`make env\` on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not commit.
ADMIN_TOKEN=$(rand)
OWNER_TOKENS=alice:$(rand),bob:$(rand)
SLACK_SIGNING_SECRET=$(rand)
API_PORT=8000
EDGE_PORT=8080
DOCKER_SOCKET_GID=${socket_gid}
EOF
echo "wrote ${TARGET} (mode 600) with fresh tokens; DOCKER_SOCKET_GID=${socket_gid}"
